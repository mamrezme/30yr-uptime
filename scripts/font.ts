/** The lit pixels of `ch` as [x, y] within its cell; an unknown glyph draws '?'. */
export function glyph(ch: string): Array<[number, number]> {
  const rows = (G[ch] ?? G['?']!).split('|').filter(r => r !== '')
  const out: Array<[number, number]> = []
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) if (row[x] === '#') out.push([x, y])
  })
  return out
}

export const hasGlyph = (ch: string) => ch in G
